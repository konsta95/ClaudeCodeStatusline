#!/usr/bin/env python3
"""Regression lab for the picker's EXIT-CODE contract.

The picker's exit code is the only channel out of a tmux pane, so a wrong code
does not merely misreport -- it misdirects. Two codes are easy to confuse and
carry opposite instructions:

    1  selftest failures -- a real defect in the picker; report it, DO NOT retry
    2  environment or usage error -- report the message; the human can fix it

Any uncaught exception in main() exits 1. So every environmental failure that
reaches the interpreter uncaught is silently relabelled as a permanent picker
defect that must not be retried, which is the opposite of the truth. This lab
pins the two places that happen, each against a KNOWN-BAD.

The known-bad is generated by MUTATING the current source -- deleting the guard
under test -- rather than by checking out an older revision. A history-based
arm stops being a known-bad the moment the fix merges; a mutant does not. Each
mutation asserts its anchor exists and fails loudly if it does not, so a
refactor that moves the guard breaks this lab instead of silently passing it.

The unsavable-directory fixture is built from ENOTDIR, not from a 0o555 mode:
permission bits are discretionary and root ignores them, which would leave the
F1 arms passing a save they were supposed to block. See cfg_unsavable, and the
assert_unsavable precondition that proves the fixture before the arms run.

Arms:
    F1  save into an unsavable config dir   mutant -> 1, real -> 2
    F1  save into a writable dir            real   -> 0   (control)
    F6  platform without termios            mutant -> 1, real -> 2

Run: python3 lab/exit_contract_lab.py     (exit 0 = all arms as expected)
"""
import os
import shutil
import subprocess
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
PICKER = os.path.join(REPO, "statusline_picker.py")
JS = os.path.join(REPO, "statusline.js")

# --- mutations -------------------------------------------------------------
# Each is (anchor, replacement). The anchor is the guard as it stands; the
# replacement is the code as it was before the fix.

F1_GUARD = """        try:
            save_config(args.config, state.enabled, state.colors,
                        state.scheme, state.item_colors)
        except OSError as exc:
            print("error: could not save %s: %s" % (args.config, exc),
                  file=sys.stderr)
            sys.exit(2)
"""
F1_UNGUARDED = """        save_config(args.config, state.enabled, state.colors,
                    state.scheme, state.item_colors)
"""

F6_GUARD = """    try:
        import termios  # noqa: F401
    except ImportError:
"""
F6_UNGUARDED = """    if False:
        import termios  # noqa: F401
    elif False:
"""

failures = []


def evidence(case, ok, detail):
    print("%-4s %-46s %s" % ("ok" if ok else "FAIL", case, detail))
    if not ok:
        failures.append(case)


def mutate(anchor, replacement, dest):
    """Write a copy of the picker with `anchor` swapped for `replacement`."""
    src = open(PICKER, encoding="utf-8").read()
    if src.count(anchor) != 1:
        raise SystemExit(
            "lab error: mutation anchor found %d times, expected exactly 1.\n"
            "The guard under test moved or changed shape; this lab is stale "
            "and would otherwise pass without measuring anything.\n---\n%s"
            % (src.count(anchor), anchor)
        )
    open(dest, "w", encoding="utf-8").write(src.replace(anchor, replacement))
    return dest


def run_picker(script, cfg, no_termios=False, keys=b"\r", settle=2.5):
    """Drive `script` through a real pty and return (exit code, last stderr line).

    A pty is required: the picker refuses to run without a tty, and the paths
    under test both sit after that check.
    """
    home = tempfile.mkdtemp(prefix="exitlab-home.")
    env = dict(os.environ, HOME=home, NO_COLOR="1")
    if no_termios:
        # What Windows does natively. Setting the entry to None makes the
        # import statement itself raise, which is the condition under test.
        shim = ("import sys, runpy;"
                "sys.modules['termios'] = None;"
                "sys.argv = ['statusline_picker.py', '--js', %r, '--config', %r];"
                "runpy.run_path(%r, run_name='__main__')" % (JS, cfg, script))
        argv = [sys.executable, "-c", shim]
    else:
        argv = [sys.executable, script, "--js", JS, "--config", cfg]

    master, slave = os.openpty()
    try:
        p = subprocess.Popen(argv, stdin=slave, stdout=slave,
                             stderr=subprocess.PIPE, text=True, env=env,
                             close_fds=True)
        os.close(slave)
        time.sleep(settle)
        try:
            os.write(master, keys)
        except OSError:
            pass  # already exited -- the environment arms do that
        try:
            _, err = p.communicate(timeout=30)
        except subprocess.TimeoutExpired:
            p.kill()
            p.communicate()
            return "TIMEOUT", ""
        lines = [l for l in (err or "").splitlines() if l.strip()]
        return p.returncode, (lines[-1] if lines else "")
    finally:
        try:
            os.close(master)
        except OSError:
            pass
        shutil.rmtree(home, ignore_errors=True)


def cfg_writable(parent):
    d = os.path.join(parent, "w")
    os.makedirs(d, exist_ok=True)
    return os.path.join(d, "statusline-config.json")


def cfg_unsavable(parent):
    """A config path whose PARENT is a regular file, so any save under it fails
    with ENOTDIR.

    The obvious construction -- a 0o555 directory -- tests a DISCRETIONARY
    permission, and root bypasses those (CAP_DAC_OVERRIDE). Run this lab under
    sudo, which this tool has been run under, and the mutant would save happily
    and exit 0: the lab would report FAILED while never once exercising the
    contract it exists to pin, and the failure would read as a regression in
    the picker rather than as a broken fixture. ENOTDIR is structural, so it
    holds at every uid. Measured: mkstemp(dir=<a regular file>) raises
    NotADirectoryError, errno 20.

    load_config catches OSError and falls back to the default selection, so the
    read at startup is unaffected and the failure lands on the save -- which is
    the site under test.
    """
    f = os.path.join(parent, "not-a-dir")
    if not os.path.exists(f):
        open(f, "w").close()
    return os.path.join(f, "statusline-config.json")


def assert_unsavable(path):
    """Prove the fixture before trusting the arms built on it.

    Without this, an environment where the save unexpectedly SUCCEEDS makes
    both F1 arms return 0 and the lab report two failures with no hint that the
    fixture, not the picker, is what broke.
    """
    try:
        fd, tmp = tempfile.mkstemp(dir=os.path.dirname(path))
    except OSError:
        return
    os.close(fd)
    os.unlink(tmp)
    raise SystemExit(
        "lab error: the F1 fixture is writable in this environment -- a save "
        "into %s succeeded.\nBoth F1 arms would exit 0 and the lab would report "
        "failures that say nothing about the picker.\nFix the fixture; do not "
        "read the arms." % os.path.dirname(path)
    )


def main():
    if not hasattr(os, "openpty"):
        print("SKIP: this lab needs a pty (no os.openpty on this platform)")
        return 0
    if not os.path.exists(JS):
        print("SKIP: renderer not found: %s" % JS)
        return 0

    tmp = tempfile.mkdtemp(prefix="exitcontract.")
    print("-- F1: an unsavable config dir must be code 2, never code 1 --")

    bad = cfg_unsavable(tmp)
    assert_unsavable(bad)

    mutant = mutate(F1_GUARD, F1_UNGUARDED, os.path.join(tmp, "f1_mutant.py"))
    rc, err = run_picker(mutant, bad)
    evidence("F1 known-bad: unguarded save exits 1", rc == 1,
             "rc=%s  %s" % (rc, err[:70]))

    rc, err = run_picker(PICKER, bad)
    evidence("F1 fixed: guarded save exits 2", rc == 2,
             "rc=%s  %s" % (rc, err[:70]))

    rc, _ = run_picker(PICKER, cfg_writable(tmp))
    evidence("F1 control: a writable dir still saves (0)", rc == 0, "rc=%s" % rc)

    print("-- F6: a platform without termios must be code 2, never code 1 --")

    mutant6 = mutate(F6_GUARD, F6_UNGUARDED, os.path.join(tmp, "f6_mutant.py"))
    rc, err = run_picker(mutant6, os.path.join(tmp, "c6.json"), no_termios=True)
    evidence("F6 known-bad: unprobed import exits 1", rc == 1,
             "rc=%s  %s" % (rc, err[:70]))

    rc, err = run_picker(PICKER, os.path.join(tmp, "c6.json"), no_termios=True)
    evidence("F6 fixed: missing termios exits 2", rc == 2,
             "rc=%s  %s" % (rc, err[:70]))

    print("---")
    print("EXIT-CONTRACT LAB %s (%d failures)"
          % ("PASSED" if not failures else "FAILED", len(failures)))
    return 0 if not failures else 1


if __name__ == "__main__":
    sys.exit(main())
